export function getProjectsByLeader(leaderId: string): Project[] {
  return projects.filter((p) => p.leaders?.includes(leaderId as never));
}

export function getProjectsBySector(sector: string): Project[] {
  return projects.filter((p) => p.sector.includes(sector as never));
}

export function getProjectsByPlatform(platformId: string): Project[] {
  return projects.filter((p) => p.platform === platformId);
}

export function getFeaturedProjects(): Project[] {
  return projects.filter((p) => p.isFeatured);
}
